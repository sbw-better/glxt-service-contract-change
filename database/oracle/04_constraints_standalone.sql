-- 项目正式业务表约束单独创建语句（对应01_schema.sql及02_analysis_log.sql）。
-- 仅适用于表和字段已经存在，但对应约束尚未创建的情况。
-- 完整执行原建表脚本后不应重复执行本文件；按查询结果仅选中缺少的语句执行。
-- 已有数据必须符合约束，否则创建失败；不删除或修正任何数据。
-- Oracle DDL自动提交，不能通过ROLLBACK撤销。请在应用实际使用的数据库用户下执行。
-- 本文件不是自动迁移脚本，不包含建表、控制行初始化、默认值、普通索引或序列。
-- DEFAULT为默认值，不是约束；主键也会保证对应字段非空。
-- NOT NULL若已存在，不要重复MODIFY；主键/唯一约束若已存在，也不要重复添加。
-- 项目分析日志采用逻辑关联，原脚本未定义物理外键，本文件不新增外键。

-- 执行前查看现有约束（P主键、U唯一、C检查/非空）。
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN (
    'TPIF_HTDLYB', 'HT_SAMPLE_LIBRARY', 'HT_ANALYSIS_LOG',
    'HT_ANALYSIS_PARA_LOG', 'HT_ANALYSIS_MATCH_LOG'
)
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;

-- 查看哪些字段已具备非空约束（NULLABLE=N）。
SELECT TABLE_NAME, COLUMN_NAME, NULLABLE, DATA_DEFAULT
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN (
    'TPIF_HTDLYB', 'HT_SAMPLE_LIBRARY', 'HT_ANALYSIS_LOG',
    'HT_ANALYSIS_PARA_LOG', 'HT_ANALYSIS_MATCH_LOG'
)
ORDER BY TABLE_NAME, COLUMN_ID;

