-- 合同历史段落语义识别服务 - Oracle 11g 初始化脚本
-- 仅用于新库初始化；已有库的约束调整与控制行初始化需另行确认。

CREATE TABLE TPIF_HTDLYB (
    ID              NUMBER(19)      NOT NULL,
    YWBW            CLOB            NOT NULL,
    GFBW            CLOB            NOT NULL,
    TEXT_HASH       VARCHAR2(64)    NOT NULL,
    BGLX_CODES      VARCHAR2(4000)  NOT NULL,
    VECTOR_DATA     CLOB            NOT NULL,
    VECTOR_DIM      NUMBER(10)      NOT NULL,
    MODEL_VERSION   VARCHAR2(100)   NOT NULL,
    SFSX            NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATE_TIME     DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TPIF_HTDLYB PRIMARY KEY (ID),
    CONSTRAINT UK_TPIF_HTDLYB_HASH UNIQUE (MODEL_VERSION, TEXT_HASH)
);

COMMENT ON TABLE TPIF_HTDLYB IS '合同历史段落与变更类型语义检索样本表';

COMMENT ON COLUMN TPIF_HTDLYB.ID IS '主键ID，由SEQ_TPIF_HTDLYB序列生成';
COMMENT ON COLUMN TPIF_HTDLYB.YWBW IS 'Excel导入的原始合同段落文本';
COMMENT ON COLUMN TPIF_HTDLYB.GFBW IS '规范化后的合同段落，用于文本Hash计算和向量生成';
COMMENT ON COLUMN TPIF_HTDLYB.TEXT_HASH IS '规范化段落的SHA-256十六进制值，用于去重和精确匹配';
COMMENT ON COLUMN TPIF_HTDLYB.BGLX_CODES IS '段落对应的变更类型编码，去重排序后以英文分号分隔';
COMMENT ON COLUMN TPIF_HTDLYB.VECTOR_DATA IS 'L2归一化后的语义向量JSON数字数组CLOB，保留完整Float32精度';
COMMENT ON COLUMN TPIF_HTDLYB.VECTOR_DIM IS '语义向量维度，由模型版本和应用配置共同确定，当前使用1024维';
COMMENT ON COLUMN TPIF_HTDLYB.MODEL_VERSION IS '生成语义向量的模型版本，不同版本向量禁止混合检索';
COMMENT ON COLUMN TPIF_HTDLYB.SFSX IS '是否参与检索：1-生效，0-停用';
COMMENT ON COLUMN TPIF_HTDLYB.CREATE_TIME IS '历史样本创建时间';

-- 历史样本主键序列。
CREATE SEQUENCE SEQ_TPIF_HTDLYB START WITH 1 INCREMENT BY 1 NOCACHE;

-- 按模型版本、向量维度和生效状态加载内存索引时使用。
CREATE INDEX IDX_HTDLYB_MODEL
    ON TPIF_HTDLYB(MODEL_VERSION, VECTOR_DIM, SFSX);

CREATE TABLE HT_SAMPLE_LIBRARY (
    ID NUMBER(1) NOT NULL,
    MODEL_NAME VARCHAR2(200),
    MODEL_VERSION VARCHAR2(100),
    VECTOR_DIM NUMBER(10),
    REVISION NUMBER(19) DEFAULT 0 NOT NULL,
    OPERATION_ID VARCHAR2(36),
    OPERATION_STATUS VARCHAR2(20) DEFAULT 'IDLE' NOT NULL,
    EXPECTED_SAMPLES NUMBER(10),
    CONSTRAINT PK_HT_SAMPLE_LIBRARY PRIMARY KEY (ID),
    CONSTRAINT CK_HT_SAMPLE_LIBRARY_ID CHECK (ID=1),
    CONSTRAINT CK_HT_SAMPLE_LIBRARY_MODEL CHECK (
        (MODEL_NAME IS NULL AND MODEL_VERSION IS NULL AND VECTOR_DIM IS NULL) OR
        (MODEL_NAME IS NOT NULL AND MODEL_VERSION IS NOT NULL AND VECTOR_DIM IS NOT NULL AND VECTOR_DIM>0)),
    CONSTRAINT CK_HT_SAMPLE_LIBRARY_STATE CHECK (
        (OPERATION_STATUS='IDLE' AND OPERATION_ID IS NULL AND EXPECTED_SAMPLES IS NULL) OR
        (OPERATION_STATUS='RUNNING' AND OPERATION_ID IS NOT NULL AND EXPECTED_SAMPLES IS NULL) OR
        (OPERATION_STATUS='DB_COMMITTED' AND OPERATION_ID IS NOT NULL AND EXPECTED_SAMPLES IS NOT NULL
            AND EXPECTED_SAMPLES>0 AND MODEL_VERSION IS NOT NULL))
);
COMMENT ON TABLE HT_SAMPLE_LIBRARY IS '单行有效样本库模型身份、修订号、写入占用与最小恢复状态';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.ID IS '控制行主键，固定为1，全表仅保存一行';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.MODEL_NAME IS '当前有效样本库实际使用的模型名称，未初始化时为空';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.MODEL_VERSION IS '当前有效样本库完整模型兼容标识，包含模型名称、维度和版本，整体比较，未初始化时为空';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.VECTOR_DIM IS '当前有效样本库实际使用的向量维度，必须为正数，未初始化时为空';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.REVISION IS '样本库修订号，初始为0，样本数据变更时递增，用于提交时校验源样本库是否变化';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.OPERATION_ID IS '当前导入或重载操作的唯一标识，用于写入互斥和恢复状态归属校验，空闲时为空';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.OPERATION_STATUS IS 'IDLE空闲，RUNNING处理中，DB_COMMITTED已提交待恢复索引';
COMMENT ON COLUMN HT_SAMPLE_LIBRARY.EXPECTED_SAMPLES IS '升级提交后严格恢复索引的预期数量，其它状态为空';
-- 显式初始化为空闲状态；字段默认值仍保留。
INSERT INTO HT_SAMPLE_LIBRARY (ID, REVISION, OPERATION_STATUS)
VALUES (1, 0, 'IDLE');

COMMIT;
